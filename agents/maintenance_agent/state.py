"""
MaintenAI— LangGraph Maintenance Copilot Agent State

Defines the typed graph state tracked across diagnostic iterations, tool calls,
retrieval evidence, and human-in-the-loop work order gates.
"""

from __future__ import annotations

from typing import Annotated, Any

from langchain_core.messages import BaseMessage
from typing_extensions import TypedDict


def merge_messages(left: list[BaseMessage], right: list[BaseMessage]) -> list[BaseMessage]:
    """Reducer to append messages to history."""
    return list(left) + list(right)


class WorkOrderDraft(TypedDict, total=False):
    """Structured work order draft generated by copilot."""

    work_order_id: str
    machine_id: str
    title: str
    category: str
    priority: str
    procedures: list[str]
    required_parts: list[str]
    citations: list[str]
    estimated_downtime_hours: float
    status: str  # DRAFT | PENDING_APPROVAL | APPROVED | REJECTED


class AgentState(TypedDict, total=False):
    """
    Main State graph container for the Maintenance Copilot Agent.
    """

    messages: Annotated[list[BaseMessage], merge_messages]
    machine_id: str | None
    equipment_type: str | None
    telemetry_data: dict[str, Any] | None
    ml_health: dict[str, Any] | None
    retrieved_docs: list[dict[str, Any]]
    work_order: WorkOrderDraft | None
    requires_human_approval: bool
    is_approved: bool
    diagnostic_summary: str | None
    error: str | None
